def blend_profile(language_lines):
    """Weight each ecosystem's tolerances by how much of the code it is."""
    total = sum(language_lines.values())
    if not total:
        return {
            "max_lines": DEFAULT_PROFILE[0],
            "max_complexity": DEFAULT_PROFILE[1],
            "max_params": DEFAULT_PROFILE[2],
            "max_nesting": DEFAULT_PROFILE[3],
            "languages": [],
        }
    values = [0.0, 0.0, 0.0, 0.0]
    for lang, lines in language_lines.items():
        profile = LANGUAGE_PROFILES.get(lang, DEFAULT_PROFILE)
        share = lines / total
        values = [v + p * share for v, p in zip(values, profile)]
    return {
        "max_lines": round(values[0]),
        "max_complexity": round(values[1]),
        "max_params": round(values[2]),
        "max_nesting": round(values[3], 1),
        "languages": sorted(language_lines, key=language_lines.get, reverse=True)[:2],
    }


def read_text(path: Path):
    try:
        if path.stat().st_size > MAX_FILE_BYTES:
            return None
        return path.read_text(errors="replace")
    except OSError:
        return None


def walk(root: Path):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            abs_path = Path(dirpath) / name
            rel = abs_path.relative_to(root)
            if any(p in ARTIFACT_DIRS for p in rel.parts[:-1]):
                continue
            yield abs_path, rel


def is_test_file(rel: Path):
    stem, suffix = rel.stem, rel.suffix
    parts = {p.lower() for p in rel.parts[:-1]}
    if parts & TEST_DIR_NAMES or suffix == ".feature":
        return True
    if suffix == ".py":
        return stem.startswith("test_") or stem.endswith("_test") or stem == "conftest"
    if suffix in JS_EXT:
        return bool(re.search(r"\.(test|spec)$", stem))
    if suffix == ".go":
        return stem.endswith("_test")
    if suffix in {".java", ".kt", ".cs"}:
        return stem.endswith(("Test", "Tests", "Spec"))
    if suffix == ".rb":
        return stem.endswith(("_spec", "_test"))
    if suffix == ".php":
        return stem.endswith("Test")
    return False


def line_of(text: str, offset: int):
    return text.count("\n", 0, offset) + 1


def body_of(text: str, start: int, lang: str):
    """The source of one function, by brace matching or by indentation."""
    if lang in BRACE_LANGS:
        opening = text.find("{", start)
        if opening == -1 or opening - start > 400:
            return text[start : start + 400]
        depth = 0
        for index in range(opening, len(text)):
            char = text[index]
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    return text[start : index + 1]
        return text[start:]
    lines = text[start:].splitlines()
    if not lines:
        return ""
    base = len(lines[0]) - len(lines[0].lstrip())
    body = [lines[0]]
    for line in lines[1:]:
        if line.strip() and (len(line) - len(line.lstrip())) <= base:
            break
        body.append(line)
    return "\n".join(body)


def signature_window(body: str, name: str, span=400):
    """The text just after a function's name, where its parameters live."""
    position = body.find(name)
    if position == -1:
        return body[:span]
    start = position + len(name)
    return body[start : start + span]


def nesting_depth(body: str, lang: str):
    if lang in BRACE_LANGS:
        depth = peak = 0
        for char in body:
            if char == "{":
                depth += 1
                peak = max(peak, depth)
            elif char == "}":
                depth = max(0, depth - 1)
        return max(0, peak - 1)
    lines = [ln for ln in body.splitlines() if ln.strip()]
    if not lines:
        return 0
    base = len(lines[0]) - len(lines[0].lstrip())
    indents = sorted({len(ln) - len(ln.lstrip()) for ln in lines[1:]})
    unit = min((i - base for i in indents if i > base), default=4) or 4
    deepest = max((len(ln) - len(ln.lstrip()) for ln in lines[1:]), default=base)
    return max(0, round((deepest - base) / unit) - 1)


# `self` is not a parameter the caller passes; counting it penalises every
# method against every free function.
IMPLICIT_FIRST_PARAM = {"python"}
IMPLICIT_NAMES = {"self", "cls", "this", "$this"}


def count_params(signature: str, implicit_self=False):
    """Count declared parameters, across line breaks and nested generics."""
    start = signature.find("(")
    if start == -1:
        return 0
    depth = 0
    collected = []
    for char in signature[start:]:
        if char in "([{":
            depth += 1
            if depth == 1:
                continue
        elif char in ")]}":
            depth -= 1
            if depth == 0:
                break
        collected.append(char)
    parts = [
        part.strip()
        for part in re.split(r",(?![^(\[{<]*[)\]}>])", "".join(collected))
        if part.strip()
    ]
    if implicit_self and parts and parts[0].split(":")[0].strip() in IMPLICIT_NAMES:
        parts = parts[1:]
    return len(parts)


# ------------------------------------------------------------- file analysis


def analyse_file(rel: Path, text: str, lang: str, profile):
    """Per-function and per-class measurements for one source file.

    Structure is read from `code` — the source with comments and string
    contents blanked — while the comment-shaped signals (TODOs, commented-out
    code) and the import and infrastructure markers are read from the original,
    where the strings they live in still exist.
    """
    func_re = FUNC_RE.get(lang)
    class_re = CLASS_RE.get(lang)
    code = strip_noise(text, lang)
    lines = [ln for ln in text.splitlines() if ln.strip()]
    info = {
        "file": str(rel),
        "lang": lang,
        "lines": len(lines),
        "code": code,
        "functions": [],
        "classes": [],
        "findings": [],
        "demeter": len(DEMETER_RE.findall(code)),
        "todos": len(TODO_RE.findall(text)),
        "commented_code": len(COMMENTED_CODE_RE.findall(text)),
        "stubs": len(STUB_RE.findall(code)),
        "globals": len(GLOBAL_STATE_RE[lang].findall(code)) if lang in GLOBAL_STATE_RE else 0,
        "infra": len(INFRA_RE.findall(text)),
        "concerns": {name for name, pattern in CONCERN_RE.items() if pattern.search(text)},
        "imports": [],
    }

    import_re = IMPORT_RE.get(lang)
    if import_re:
        for match in import_re.finditer(text):
            for group in match.groups():
                if not group:
                    continue
                for part in group.split(","):
                    target = part.strip().strip("()").split(" as ")[0].strip()
                    if target:
                        info["imports"].append(target)

    if class_re:
        for match in class_re.finditer(code):
            name = match.group(1)
            bases = (
                (match.group(2) or "").strip() if match.lastindex and match.lastindex > 1 else ""
            )
            info["classes"].append(
                {"name": name, "bases": bases, "line": line_of(code, match.start())}
            )

    if func_re:
        for match in func_re.finditer(code):
            groups = [g for g in match.groups() if g is not None]
            name = groups[-1] if groups else "?"
            if name in {"if", "for", "while", "switch", "catch", "return"}:
                continue
            body = body_of(code, match.start(), lang)
            body_lines = [ln for ln in body.splitlines() if ln.strip()]
            function = {
                "name": name,
                "line": line_of(code, match.start()),
                "lines": len(body_lines),
                "complexity": 1 + len(DECISION_RE.findall(body)),
                "nesting": nesting_depth(body, lang),
                "params": count_params(
                    signature_window(body, name), implicit_self=lang in IMPLICIT_FIRST_PARAM
                ),
                "flag_params": len(
                    re.findall(r"=\s*(?:True|False|true|false)\b", body.split("\n", 1)[0])
                ),
                "body": body,
            }
            info["functions"].append(function)
            for label, value, limit, kind in (
                ("lines", function["lines"], profile["max_lines"], "long-function"),
                (
                    "complexity",
                    function["complexity"],
                    profile["max_complexity"],
                    "complex-function",
                ),
                ("nesting", function["nesting"], profile["max_nesting"], "deep-nesting"),
                ("params", function["params"], profile["max_params"], "many-parameters"),
            ):
                if value > limit:
                    info["findings"].append(
                        {
                            "file": str(rel),
                            "line": function["line"],
                            "kind": kind,
                            "message": f"`{name}` has {value} {label} (limit {limit:g})",
                        }
                    )
    return info


NORMALISE_RE = re.compile(r"'[^'\n]*'|\"[^\"\n]*\"|`[^`\n]*`|\b\d+(?:\.\d+)?\b")
COMMENT_LINE_RE = re.compile(r"^[ \t]*(?:#|//|\*|/\*)")


def normalise_line(line: str):
    return re.sub(r"\s+", " ", NORMALISE_RE.sub("@", line)).strip()


STATEMENT_RE = re.compile(r"[-+*/%=<>!]=?|\breturn\b|\bif\b|\bfor\b|\bwhile\b|\w+\s*\(")
DECLARATION_RE = re.compile(r"^\s*(?:import|from|package|use|require|#include|\w+\s*:\s*[\"'@])")


def find_duplicate_blocks(files, window=8, limit=20):
    """Windows of consecutive lines that appear verbatim somewhere else.

    Framework boilerplate — a struct literal of declarations, a block of
    imports — repeats legitimately and would otherwise dominate, so a window
    only counts when most of it is actual statements.
    """
    seen = {}
    duplicated_lines = set()
    findings = []
    reported = set()
    for path, text in files:
        rows = [
            (index + 1, normalise_line(line))
            for index, line in enumerate(text.splitlines())
            if line.strip() and not COMMENT_LINE_RE.match(line)
        ]
        for start in range(len(rows) - window + 1):
            chunk = rows[start : start + window]
            block = "\n".join(line for _, line in chunk)
            if len(block) < window * 14:
                continue
            statements = sum(
                1
                for _, line in chunk
                if STATEMENT_RE.search(line) and not DECLARATION_RE.match(line)
            )
            if statements < window * 0.6:
                continue
            origin = seen.get(block)
            if origin is None:
                seen[block] = (path, chunk[0][0])
                continue
            if origin[0] == path and abs(origin[1] - chunk[0][0]) < window:
                continue
            # Sliding windows overlap, so each duplicated line is counted once:
            # summing window lengths can report more duplicated lines than the
            # file has.
            duplicated_lines.update((path, number) for number, _ in chunk)
            key = (path, chunk[0][0] // window)
            if key not in reported and len(findings) < limit:
                reported.add(key)
                findings.append(
                    {
                        "file": path,
                        "line": chunk[0][0],
                        "kind": "duplicate-block",
                        "message": f"{window} lines repeated from {origin[0]}:{origin[1]}",
                    }
                )
    return len(duplicated_lines), findings


def find_cycles(graph, limit=10):
    """Import cycles between the repo's own modules."""
    colour = {}
    stack = []
    cycles = []

    def visit(node):
        colour[node] = 1
        stack.append(node)
        for neighbour in sorted(graph.get(node, ())):
            if colour.get(neighbour, 0) == 0:
                visit(neighbour)
            elif colour.get(neighbour) == 1 and len(cycles) < limit:
                start = stack.index(neighbour)
                cycles.append(stack[start:] + [neighbour])
        stack.pop()
        colour[node] = 2

    for node in sorted(graph):
        if colour.get(node, 0) == 0:
            visit(node)
    return cycles


# ------------------------------------------------------------------- churn

FIX_LIMIT = 800


def git_churn(root: Path, limit=FIX_LIMIT):
    """How many commits touched each file, keyed the same way as the scan.

    `git log` reports paths from the repository root, so when the scan starts
    in a subdirectory the prefix is stripped — otherwise nothing ever matches
    and the dimension silently scores nothing.
    """

    def run(*args):
        try:
            result = subprocess.run(
                ["git", "-C", str(root), *args],
                capture_output=True,
                text=True,
                timeout=60,
                check=False,
            )
        except (OSError, subprocess.SubprocessError):
            return None
        return result.stdout if result.returncode == 0 else None

    prefix = run("rev-parse", "--show-prefix")
    if prefix is None:
        return {}
    prefix = prefix.strip()
    log = run(
        "log", "-n", str(limit), "--no-merges", "--name-only", "--pretty=format:%x00", "--", "."
    )
    if not log:
        return {}
    counts = Counter()
    for line in log.splitlines():
        path = line.strip()
        if not path or path.startswith("\x00"):
            continue
        if prefix:
            if not path.startswith(prefix):
                continue
            path = path[len(prefix) :]
        counts[path] += 1
    return dict(counts)


def find_hotspots(churn_counts, file_complexity, limit=10):
    """Complexity that sits where the changes land is the expensive kind."""
    scored = [
        (path, churn_counts.get(path, 0), complexity)
        for path, complexity in file_complexity.items()
    ]
    changed = [entry for entry in scored if entry[1] > 1]
    # Enough files to have a meaningful average, and enough churn to rank by.
    # Three files hammered while the rest sit still is the hotspot case, not a
    # reason to give up on it.
    if len(scored) < 5 or len(changed) < 3:
        return None
    changed.sort(key=lambda entry: (-entry[1], entry[0]))
    hot_count = max(3, round(len(changed) * 0.2))
    hot = changed[:hot_count]
    overall = sum(complexity for _, _, complexity in scored) / max(len(scored), 1)
    hot_average = sum(complexity for _, _, complexity in hot) / len(hot)
    findings = []
    for path, commits, complexity in sorted(hot, key=lambda e: -(e[1] * e[2])):
        if complexity <= overall or len(findings) >= limit:
            continue
        findings.append(
            {
                "file": path,
                "line": 1,
                "kind": "hotspot",
                "message": f"changed {commits} times and carries {complexity} complexity "
                f"(codebase average {overall:.0f}) — the expensive kind",
            }
        )
    return {
        "hot_files": len(hot),
        "hot_complexity": round(hot_average, 1),
        "average_complexity": round(overall, 1),
        "findings": findings,
    }


